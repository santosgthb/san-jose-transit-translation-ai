const locale: Record<Language, string> = {
  vi: 'vi-VN',
  en: 'en-US',
  es: 'es-US',
  pa: 'pa-IN',
};

const inputLanguages: Record<Language, string> = {
  vi: 'Tiếng Việt',
  en: 'English',
  es: 'Español',
  pa: 'ਪੰਜਾਬੀ',
};

function SubmissionCard({ submission, language }: { submission: RiderSubmission; language: Language }) {
  const t = content[language];
  const responseKind = (submission as RiderSubmission & { responseKind?: string }).responseKind;
  const responseDisclaimer = responseKind === 'ai_generated'
    ? t.responseAi
    : responseKind === 'context_only'
      ? t.responseContext
      : t.responseLegacy;
  return (
    <article className="rounded-[20px] border border-[hsl(var(--border))] bg-[hsl(var(--card))] p-4 shadow-[0_10px_24px_hsl(216_61%_20%/.05)] sm:rounded-[24px] sm:p-7" data-testid={`card-submission-${submission.id}`}>
      <div className="flex flex-wrap items-start justify-between gap-3 border-b border-[hsl(var(--border))] pb-4">
        <div>
          <p className="font-mono text-sm font-bold text-[hsl(var(--primary))]" data-testid={`text-reference-${submission.id}`}>{submission.reference}</p>
          <p className="mt-1 text-xs text-[hsl(var(--muted-foreground))]">{t.language}: {inputLanguages[submission.language]}</p>
          <p className="mt-1 text-xs font-semibold text-[hsl(var(--muted-foreground))]" data-testid={`text-data-source-${submission.id}`}>{t.dataSource}: {submission.dataSource}</p>
        </div>
        <time dateTime={submission.submittedAt} className="flex items-center gap-1.5 text-xs text-[hsl(var(--muted-foreground))]" data-testid={`text-submitted-at-${submission.id}`}>
          <Clock3 size={15} />
          {new Intl.DateTimeFormat(locale[language], { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(submission.submittedAt))}
        </time>
      </div>
      <div className="mt-5">
        <h2 className="text-xs font-bold uppercase tracking-[.08em] text-[hsl(var(--muted-foreground))]">{t.input}</h2>
        {submission.description && <p className="mt-2 whitespace-pre-wrap break-words text-sm leading-7" data-testid={`text-input-${submission.id}`}>{submission.description}</p>}
        {submission.imageName && (
          <p className="mt-3 flex items-center gap-2 break-all text-xs font-semibold text-[hsl(var(--primary))]" data-testid={`text-image-name-${submission.id}`}>
            <ImagePlus size={16} className="shrink-0" />{t.attachment}: {submission.imageName}
          </p>
        )}
      </div>
      <div className="mt-5 rounded-2xl border border-[hsl(var(--accent)/.6)] bg-[hsl(var(--accent)/.15)] p-4">
        <h2 className="text-xs font-bold uppercase tracking-[.08em] text-[hsl(var(--primary))]">{t.response}</h2>
        <p className="mt-2 whitespace-pre-wrap text-sm leading-6" data-testid={`text-response-${submission.id}`}>{submission.assistantResponse}</p>
        <p className="mt-2 text-xs leading-5 text-[hsl(var(--muted-foreground))]">{responseDisclaimer}</p>
      </div>
      <StaffResponseStatus submission={submission} language={language} />
      <TransitDetails submission={submission} language={language} />
    </article>
  );
}

export default function RecordsPage({ language }: { language: Language }) {
  const t = content[language];
  const { data, isLoading, isError, refetch, isFetching } = useListSubmissions({ query: { queryKey: getListSubmissionsQueryKey(), refetchInterval: 30_000 } });
  const [referenceFilter, setReferenceFilter] = useState('');
  const [sourceFilter, setSourceFilter] = useState<ReportSourceFilter>('any');
  const [languageFilter, setLanguageFilter] = useState<ReportLanguageFilter>('any');
  const [responseFilter, setResponseFilter] = useState<ReportResponseFilter>('any');
  const filters = { reference: referenceFilter, source: sourceFilter, language: languageFilter, responseStatus: responseFilter };
  const matchingReports = filterReports(data ?? [], filters);
  const filtersActive =
    referenceFilter.trim().length > 0 || sourceFilter !== 'any' || languageFilter !== 'any' || responseFilter !== 'any';

  return (
    <div className="mx-auto max-w-2xl" data-testid="screen-records">
      <div className="mb-8">
        <p className="mb-3 font-mono text-[11px] font-bold uppercase tracking-[.16em] text-[hsl(var(--primary))]">{t.eyebrow}</p>
        <h1 className="text-4xl font-bold tracking-[-.06em] sm:text-5xl" data-testid="text-records-title">{t.title}</h1>
        <p className="mt-4 text-base leading-7 text-[hsl(var(--muted-foreground))]">{t.introduction}</p>
      </div>
      <div className="mb-5 flex justify-end">
        <button type="button" onClick={() => refetch()} disabled={isFetching} className="focus-ring flex min-h-11 items-center gap-2 rounded-xl border border-[hsl(var(--border))] bg-[hsl(var(--card))] px-4 text-sm font-bold text-[hsl(var(--primary))] disabled:opacity-60" data-testid="button-refresh-records">
          <RefreshCw size={16} className={isFetching ? 'animate-spin' : ''} />{t.refresh}
        </button>
      </div>
      {isLoading ? (
        <p className="rounded-2xl bg-[hsl(var(--card))] p-6 text-sm" role="status" data-testid="status-records-loading">{t.loading}</p>
      ) : isError ? (
        <div className="rounded-2xl border border-[hsl(var(--destructive)/.3)] bg-[hsl(var(--card))] p-6 text-sm" role="alert" data-testid="status-records-error">
          <p className="flex items-center gap-2 text-[hsl(var(--destructive))]"><AlertCircle size={18} />{t.error}</p>
          <button type="button" onClick={() => refetch()} className="focus-ring mt-3 font-bold underline" data-testid="button-retry-records">{t.retry}</button>
        </div>
      ) : data?.length ? (
        <div className="space-y-5">
          <section
            className="grid gap-3 rounded-2xl border border-[hsl(var(--border))] bg-[hsl(var(--card))] p-4 sm:grid-cols-2 sm:p-5"
            aria-label={`${t.filterReference}, ${t.filterSource}, ${t.filterLanguage}, ${t.filterResponse}`}
            data-testid="filters-records"
          >
            <label className="block text-xs font-bold text-[hsl(var(--muted-foreground))] sm:col-span-2">
              {t.filterReference}
              <input
                type="search"
                value={referenceFilter}
                onChange={(event) => setReferenceFilter(event.target.value)}
                placeholder={t.referencePlaceholder}
                maxLength={80}
                className="focus-ring mt-2 min-h-11 w-full rounded-xl border border-[hsl(var(--input))] bg-[hsl(var(--background))] px-3 text-sm font-medium text-[hsl(var(--foreground))] placeholder:text-[hsl(var(--muted-foreground))]"
                data-testid="input-filter-reference"
              />
            </label>
            <label className="block text-xs font-bold text-[hsl(var(--muted-foreground))]">
              {t.filterSource}
              <select
                value={sourceFilter}
                onChange={(event) => setSourceFilter(event.target.value as ReportSourceFilter)}
                className="focus-ring mt-2 min-h-11 w-full rounded-xl border border-[hsl(var(--input))] bg-[hsl(var(--background))] px-3 text-sm font-medium text-[hsl(var(--foreground))]"
                data-testid="select-filter-source"
              >
                <option value="any">{t.sourceAny}</option>
                <option value="rider">{t.sourceRider}</option>
                <option value="511">{t.source511}</option>
                <option value="ai">{t.sourceAi}</option>
              </select>
            </label>
            <label className="block text-xs font-bold text-[hsl(var(--muted-foreground))]">
              {t.filterLanguage}
              <select
                value={languageFilter}
                onChange={(event) => setLanguageFilter(event.target.value as ReportLanguageFilter)}
                className="focus-ring mt-2 min-h-11 w-full rounded-xl border border-[hsl(var(--input))] bg-[hsl(var(--background))] px-3 text-sm font-medium text-[hsl(var(--foreground))]"
                data-testid="select-filter-language"
              >
                <option value="any">{t.languageAny}</option>
                {(Object.keys(inputLanguages) as Language[]).map((option) => (
                  <option key={option} value={option}>{inputLanguages[option]}</option>
                ))}
              </select>
            </label>
            <label className="block text-xs font-bold text-[hsl(var(--muted-foreground))] sm:col-span-2">
              {t.filterResponse}
              <select value={responseFilter} onChange={event => setResponseFilter(event.target.value as ReportResponseFilter)}
                className="focus-ring mt-2 min-h-11 w-full rounded-xl border border-[hsl(var(--input))] bg-[hsl(var(--background))] px-3 text-sm font-medium text-[hsl(var(--foreground))]"
                data-testid="select-filter-response">
                <option value="any">{t.responseAny}</option>
                <option value="responded">{t.responded}</option>
                <option value="not_responded">{t.notResponded}</option>
              </select>
            </label>
            <div className="flex items-center justify-between gap-3 text-xs text-[hsl(var(--muted-foreground))] sm:col-span-2">
              <p role="status" aria-live="polite" data-testid="text-filter-count">
                {t.resultCount.replace('{shown}', String(matchingReports.length)).replace('{total}', String(data.length))}
              </p>
              {filtersActive && (
                <button
                  type="button"
                  onClick={() => {
                    setReferenceFilter('');
                    setSourceFilter('any');
                    setLanguageFilter('any');
                    setResponseFilter('any');
                  }}
                  className="focus-ring min-h-10 rounded-lg px-2 font-bold text-[hsl(var(--primary))] underline underline-offset-2"
                  data-testid="button-clear-filters"
                >
                  {t.clearFilters}
                </button>
              )}
            </div>
          </section>
          {matchingReports.length ? (
            <div className="space-y-4" data-testid="list-records">
              {matchingReports.map((submission) => <SubmissionCard key={submission.id} submission={submission} language={language} />)}
            </div>
          ) : (
            <div className="rounded-[24px] border border-[hsl(var(--border))] bg-[hsl(var(--card))] p-8 text-center" role="status" data-testid="status-records-no-matches">
              <Inbox size={34} className="mx-auto text-[hsl(var(--primary))]" />
              <h2 className="mt-4 text-xl font-bold">{t.noMatches}</h2>
              <p className="mt-2 text-sm text-[hsl(var(--muted-foreground))]">{t.filterHelp}</p>
            </div>
          )}
        </div>
      ) : (
        <div className="rounded-[24px] border border-[hsl(var(--border))] bg-[hsl(var(--card))] p-8 text-center" data-testid="status-records-empty">
          <Inbox size={34} className="mx-auto text-[hsl(var(--primary))]" />
          <h2 className="mt-4 text-xl font-bold">{t.empty}</h2>
          <p className="mt-2 text-sm text-[hsl(var(--muted-foreground))]">{t.emptyHelp}</p>
        </div>
      )}
      <p className="mt-6 text-xs leading-6 text-[hsl(var(--muted-foreground))]">{t.note}</p>
    </div>
  );
}